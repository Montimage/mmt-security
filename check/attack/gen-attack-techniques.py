#!/usr/bin/env python3
"""Build the offline list of valid MITRE ATT&CK Enterprise techniques.

The list is read by check/attack/check-attack.py (make check-attack), so that
the check of rules/mitre-attack.csv needs no network.

Usage:
    python3 check/attack/gen-attack-techniques.py --version 20.1
    python3 check/attack/gen-attack-techniques.py --version 20.1 --bundle enterprise-attack-20.1.json

Without --bundle, the bundle is downloaded from MITRE's attack-stix-data
repository, at the release tag v<version>. The output keeps every technique
and sub-technique of that release that is neither revoked nor deprecated,
with its name and its tactics (the bundle's x-mitre-tactic names, joined by
';'). See readme.md, "MITRE ATT&CK mapping", to move to a newer version.
"""

import argparse
import csv
import hashlib
import json
import os
import sys
import urllib.request

URL = ("https://raw.githubusercontent.com/mitre-attack/attack-stix-data/"
       "v{v}/enterprise-attack/enterprise-attack-{v}.json")
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "enterprise-attack-techniques.csv")


def technique_id(obj):
    for ref in obj.get("external_references", []):
        if ref.get("source_name") == "mitre-attack":
            return ref.get("external_id")
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version", required=True, help="ATT&CK release, e.g. 20.1")
    ap.add_argument("--bundle", help="local enterprise-attack-<version>.json (default: download it)")
    ap.add_argument("--out", default=DEFAULT_OUT, help="output CSV (default: %(default)s)")
    args = ap.parse_args()

    url = URL.format(v=args.version)
    if args.bundle:
        with open(args.bundle, "rb") as f:
            raw = f.read()
    else:
        print("downloading " + url, file=sys.stderr)
        with urllib.request.urlopen(url) as r:
            raw = r.read()
    sha256 = hashlib.sha256(raw).hexdigest()
    objects = json.loads(raw)["objects"]

    collection = [o for o in objects if o.get("type") == "x-mitre-collection"]
    found = collection[0].get("x_mitre_version") if collection else None
    if found != args.version:
        sys.exit("error: the bundle is ATT&CK %s, not %s" % (found, args.version))

    tactics = {}
    for o in objects:
        if o.get("type") == "x-mitre-tactic" and not o.get("revoked") and not o.get("x_mitre_deprecated"):
            tactics[o["x_mitre_shortname"]] = o["name"]

    rows = []
    for o in objects:
        if o.get("type") != "attack-pattern" or o.get("revoked") or o.get("x_mitre_deprecated"):
            continue
        tid = technique_id(o)
        if not tid:
            continue
        names = [tactics[p["phase_name"]] for p in o.get("kill_chain_phases", [])
                 if p.get("kill_chain_name") == "mitre-attack" and p.get("phase_name") in tactics]
        rows.append((tid, o["name"], ";".join(names)))

    # a sub-technique is shown as "<parent name>: <sub-technique name>", as on attack.mitre.org
    parents = {tid: name for tid, name, _ in rows if "." not in tid}
    orphans = [tid for tid, _, _ in rows if "." in tid and tid.split(".")[0] not in parents]
    if orphans:
        sys.exit("error: sub-techniques without a live parent technique: " + ", ".join(orphans))
    rows = [(tid, parents[tid.split(".")[0]] + ": " + name if "." in tid else name, tac)
            for tid, name, tac in rows]
    rows.sort(key=lambda r: [int(x) for x in r[0][1:].split(".")])

    with open(args.out, "w", newline="", encoding="utf-8") as f:
        f.write("# MITRE ATT&CK Enterprise %s\n" % args.version)
        f.write("# source: %s\n" % url)
        f.write("# sha256: %s\n" % sha256)
        f.write("# generated by check/attack/gen-attack-techniques.py: do not edit by hand\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["technique_id", "technique_name", "tactics"])
        w.writerows(rows)
    print("wrote %d techniques of ATT&CK Enterprise %s to %s" % (len(rows), args.version, args.out),
          file=sys.stderr)


if __name__ == "__main__":
    main()
